def parse() -> list[dict]:
    rows = []
    for line in RAW.strip().splitlines():
        day, direction, category, amount, detail = line.split("|")
        rows.append(
            {
                "date": day,
                "direction": direction,
                "category": category,
                "amount": Decimal(amount),
                "detail": detail,
                "signed": Decimal(amount) if direction == "收入" else -Decimal(amount),
            }
        )
    return rows


def summarize(rows: list[dict]) -> None:
    total = sum((r["signed"] for r in rows), Decimal("0"))
    by_cat: dict[str, dict[str, Decimal]] = defaultdict(lambda: defaultdict(Decimal))
    for r in rows:
        by_cat[r["category"]]["in" if r["direction"] == "收入" else "out"] += r["amount"]
    print(f"WPS 记账明细 {len(rows)} 条，净额 {total:,.2f}")
    print(f"{'类别':<8}{'笔数':>5}{'收入':>14}{'支出':>14}{'净额':>14}")
    for cat, agg in sorted(by_cat.items(), key=lambda kv: -(kv[1]["in"] + kv[1]["out"])):
        n = sum(1 for r in rows if r["category"] == cat)
        print(f"{cat:<8}{n:>5}{agg['in']:>14,.2f}{agg['out']:>14,.2f}{agg['in'] - agg['out']:>14,.2f}")


